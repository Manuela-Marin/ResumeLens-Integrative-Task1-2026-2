def _quote(text):
    """Return a textX STRING literal for `text`."""
    if text is None:
        text = ""
    escaped = str(text).replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped + '"'


def _note_for(result):
    """Return the human readable explanation of one evaluation."""
    readable = result["profile"].replace("_", " ").title()
    if result["verdict"] == "ACCEPTED":
        return ("The normalized qualifications satisfy an accepted " +
                readable + " pattern.")
    if result["missing"]:
        return ("The pattern is not satisfied; missing required stages: " +
                ", ".join(result["missing"]) + ".")
    return "The pattern is not satisfied."


def build(extracted, canonical_skills, results):
    """Build a sentence of the candidate profile language."""
    lines = []
    lines.append("// Candidate profile generated by ResumeLens")
    lines.append("candidate " + _quote(extracted.get("name")) + " {")

    lines.append("    contact {")
    lines.append("        email " + (extracted.get("email") or
                                     "unknown@example.com"))
    if extracted.get("phone"):
        lines.append("        phone " + _quote(extracted["phone"]))
    if extracted.get("location"):
        lines.append("        location " + _quote(extracted["location"]))
    if extracted.get("role"):
        lines.append("        role " + _quote(extracted["role"]))
    lines.append("    }")

    if extracted.get("summary"):
        lines.append("    summary " + _quote(extracted["summary"]))

    if extracted.get("education"):
        lines.append("    education {")
        for record in extracted["education"]:
            lines.append("        degree " +
                         _quote(record["degree"] + " in " + record["field"]))
            lines.append("        institution " +
                         _quote(record["institution"]))
            lines.append("        year " + str(record["year"]))
        lines.append("    }")

    if extracted.get("experience"):
        lines.append("    experience {")
        for record in extracted["experience"]:
            lines.append("        position " + _quote(record["title"]))
            lines.append("        organization " +
                         _quote(record["organization"]))
            lines.append("        years " + str(record["years"]))
            if record["responsibilities"]:
                lines.append("        responsibilities {")
                for item in record["responsibilities"]:
                    lines.append("            " + _quote(item))
                lines.append("        }")
        lines.append("    }")

    lines.append("    skills {")
    if canonical_skills:
        lines.append("        " + " ".join(canonical_skills))
    lines.append("    }")

    for result in results:
        lines.append("    evaluation " + result["profile"] + " {")
        lines.append("        pattern " + result["verdict"])
        if result["sequence"]:
            lines.append("        sequence {")
            lines.append("            " + " ".join(result["sequence"]))
            lines.append("        }")
        lines.append("        note " + _quote(_note_for(result)))
        lines.append("    }")

    lines.append("}")
    return "\n".join(lines) + "\n"