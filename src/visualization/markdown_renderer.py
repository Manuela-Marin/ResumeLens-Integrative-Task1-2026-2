from .html_renderer import _readable


def render_markdown(model):
    """Return the Markdown visualization of a validated candidate profile."""
    lines = []
    lines.append("# " + str(model.name))
    lines.append("")
    lines.append("Candidate Profile generated by ResumeLens")
    lines.append("")

    lines.append("## Personal Information")
    lines.append("")
    lines.append("- **Email:** " + str(model.contact.email))
    if model.contact.phone:
        lines.append("- **Phone:** " + str(model.contact.phone))
    if model.contact.location:
        lines.append("- **Location:** " + str(model.contact.location))
    if model.contact.role:
        lines.append("- **Current role:** " + str(model.contact.role))
    lines.append("")

    if model.summary:
        lines.append("## Profile Summary")
        lines.append("")
        lines.append(str(model.summary))
        lines.append("")

    if model.education:
        lines.append("## Education")
        lines.append("")
        for record in model.education:
            lines.append("- " + str(record.degree) + " - " +
                         str(record.institution) +
                         " (" + str(record.year) + ")")
        lines.append("")

    if model.experience:
        lines.append("## Experience")
        lines.append("")
        for record in model.experience:
            lines.append("### " + str(record.title))
            lines.append("")
            lines.append(str(record.organization) + " - " +
                         str(record.years) + " years")
            lines.append("")
            for item in record.responsibilities:
                lines.append("- " + str(item))
            lines.append("")

    lines.append("## Normalized Technical Skills")
    lines.append("")
    lines.append(", ".join(str(skill) for skill in model.skills))
    lines.append("")

    lines.append("## Qualification Evaluation")
    lines.append("")
    lines.append("| Profile | Pattern | Sequence read |")
    lines.append("|---|---|---|")
    for evaluation in model.evaluations:
        sequence = ", ".join(str(item) for item in evaluation.sequence)
        lines.append("| " + _readable(evaluation.profile) +
                     " | " + str(evaluation.verdict) +
                     " | " + sequence + " |")
    lines.append("")
    for evaluation in model.evaluations:
        if evaluation.note:
            lines.append("- **" + _readable(evaluation.profile) + ":** " +
                         str(evaluation.note))
    lines.append("")
    return "\n".join(lines)