def _escape(text):
    """Escape the characters that are special in HTML."""
    if text is None:
        return ""
    return (str(text)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;"))


def _readable(profile_name):
    """Turn FULL_STACK_DEVELOPER into Full Stack Developer."""
    return profile_name.replace("_", " ").title()


def render_html(model):
    """Return the HTML visualization of a validated candidate profile."""
    parts = []
    parts.append("<!DOCTYPE html>")
    parts.append('<html lang="en">')
    parts.append("<head>")
    parts.append('    <meta charset="UTF-8">')
    parts.append('    <meta name="viewport" '
                 'content="width=device-width, initial-scale=1.0">')
    parts.append("    <title>ResumeLens - Candidate Profile</title>")
    parts.append("    <style>")
    parts.append(STYLE)
    parts.append("    </style>")
    parts.append("</head>")
    parts.append("<body>")
    parts.append('<div class="candidate-card">')

    # Candidate identification.
    parts.append('    <div class="header">')
    parts.append("        <h1>" + _escape(model.name) + "</h1>")
    parts.append("        <p>Candidate Profile generated by ResumeLens</p>")
    parts.append("    </div>")

    # Personal information.
    parts.append('    <div class="section">')
    parts.append("        <h2>Personal Information</h2>")
    parts.append("        <p><strong>Email:</strong> " +
                 _escape(model.contact.email) + "</p>")
    if model.contact.phone:
        parts.append("        <p><strong>Phone:</strong> " +
                     _escape(model.contact.phone) + "</p>")
    if model.contact.location:
        parts.append("        <p><strong>Location:</strong> " +
                     _escape(model.contact.location) + "</p>")
    if model.contact.role:
        parts.append("        <p><strong>Current role:</strong> " +
                     _escape(model.contact.role) + "</p>")
    parts.append("    </div>")

    # Profile summary.
    if model.summary:
        parts.append('    <div class="section">')
        parts.append("        <h2>Profile Summary</h2>")
        parts.append("        <p>" + _escape(model.summary) + "</p>")
        parts.append("    </div>")

    # Education.
    if model.education:
        parts.append('    <div class="section">')
        parts.append("        <h2>Education</h2>")
        for record in model.education:
            parts.append("        <p>" + _escape(record.degree) +
                         ' <span class="metadata">' +
                         _escape(record.institution) + " &middot; " +
                         str(record.year) + "</span></p>")
        parts.append("    </div>")

    # Experience.
    if model.experience:
        parts.append('    <div class="section">')
        parts.append("        <h2>Experience</h2>")
        for record in model.experience:
            parts.append("        <h3>" + _escape(record.title) + "</h3>")
            parts.append('        <p class="metadata">' +
                         _escape(record.organization) + " &middot; " +
                         str(record.years) + " years</p>")
            if record.responsibilities:
                parts.append("        <ul>")
                for item in record.responsibilities:
                    parts.append("            <li>" + _escape(item) + "</li>")
                parts.append("        </ul>")
        parts.append("    </div>")

    # Normalized technical skills.
    parts.append('    <div class="section">')
    parts.append("        <h2>Normalized Technical Skills</h2>")
    parts.append('        <div class="skills">')
    for skill in model.skills:
        parts.append('            <span class="skill">' + _escape(skill) +
                     "</span>")
    parts.append("        </div>")
    parts.append("    </div>")

    # Qualification evaluation.
    parts.append('    <div class="section">')
    parts.append("        <h2>Qualification Evaluation</h2>")
    for evaluation in model.evaluations:
        parts.append('        <div class="evaluation">')
        parts.append("            <p><strong>Profile evaluated:</strong> " +
                     _readable(evaluation.profile) + "</p>")
        parts.append("            <p><strong>Qualification pattern:</strong> "
                     '<span class="accepted">' + _escape(evaluation.verdict) +
                     "</span></p>")
        if evaluation.sequence:
            parts.append("            <p><strong>Sequence read:</strong> " +
                         _escape(", ".join(evaluation.sequence)) + "</p>")
        if evaluation.note:
            parts.append("            <p>" + _escape(evaluation.note) + "</p>")
        parts.append("        </div>")
    parts.append("    </div>")

    parts.append("</div>")
    parts.append("</body>")
    parts.append("</html>")
    return "\n".join(parts) + "\n"